"""Generate Ritrovato logo SVGs (peeking lost-and-found box) from one shape set.

Run: python docs/brand/gen_logo.py
Writes docs/brand/logo.svg (master with glow), docs/brand/logo-icon.svg (app icon),
web/public/favicon.svg and web/src/components/Logo.tsx (eyes crop for small sizes). PNGs in docs/brand/ and web/public/apple-touch-icon.png
were exported from these SVGs with headless Chrome. Traced from logo-source.png.
"""
import pathlib, re

REPO = pathlib.Path(__file__).resolve().parents[2]

# Site palette (web/src/index.css): card, manila, ink, signal.
C = dict(bg="#f7f7f3", box="#e6d3a0", gap="#111111", line="#111111", eye="#ffffff", ink="#111111",
         tag="#f7f7f3", tagline="#111111", bang="#ff5a1f")


def shapes(sw, simple=False, c=C):
    """Mark in 1254-px source coordinates. sw = outline stroke width."""
    base = '' if simple else f'''
  <ellipse cx="630" cy="857" rx="308" ry="21" fill="{c['box']}" stroke="{c['line']}" stroke-width="{sw*0.8:.1f}"/>'''
    rim = '' if simple else f'''
  <path d="M378 572 L858 420" fill="none" stroke="{c['line']}" stroke-width="{sw*0.55:.1f}" stroke-linecap="round" opacity="0.55"/>'''
    return base + f'''
  <path d="M366 612 L520 548 L880 440 L904 622 Z" fill="{c['gap']}"/>
  <circle cx="620" cy="566" r="47" fill="{c['eye']}"/>
  <circle cx="728" cy="556" r="47" fill="{c['eye']}"/>
  <circle cx="646" cy="560" r="25" fill="{c['ink']}"/>
  <circle cx="750" cy="546" r="25" fill="{c['ink']}"/>
  <circle cx="656" cy="549" r="7.5" fill="{c['eye']}"/>
  <circle cx="760" cy="535" r="7.5" fill="{c['eye']}"/>
  <path d="M345 622 Q627 604 910 622 L884 828 Q882 846 864 846 L398 846 Q380 846 378 828 Z"
        fill="{c['box']}" stroke="{c['line']}" stroke-width="{sw}" stroke-linejoin="round"/>
  <path d="M341 592 L388 452 Q394 436 410 432 L806 352 Q824 349 836 362 L894 414 Q904 426 889 432 L360 604 Q338 611 341 592 Z"
        fill="{c['box']}" stroke="{c['line']}" stroke-width="{sw}" stroke-linejoin="round"/>{rim}
  <path d="M742 624 C770 640 774 684 760 714" fill="none" stroke="{c['line']}" stroke-width="{sw*0.75:.1f}" stroke-linecap="round"/>
  <g transform="translate(742 764) rotate(20)">
    <path d="M-36 -32 L-17 -50 H17 L36 -32 V46 Q36 52 30 52 H-30 Q-36 52 -36 46 Z" fill="{c['tag']}" stroke="{c['tagline']}" stroke-width="{sw*0.6:.1f}" stroke-linejoin="round"/>
    <circle cx="0" cy="-33" r="7.5" fill="{c['box']}"/>
  </g>
  <path d="M836 288 L842 350 M936 330 L894 376" fill="none" stroke="{c['bang']}" stroke-width="{sw*2:.0f}" stroke-linecap="round"/>'''


def master(size=1024):
    # Full mark on a flat square, roomy framing for slides and the video.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="136 85 1000 1000" width="{size}" height="{size}">
  <title>Ritrovato</title>
  <rect x="136" y="85" width="1000" height="1000" fill="{C['bg']}"/>{shapes(16)}
</svg>
'''


def icon(stroke=20, c=C):
    # App-icon badge: rounded dark square, no glow, heavier outlines so it survives 16-32 px.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="276 238 712 712">
  <title>Ritrovato</title>
  <rect x="276" y="238" width="712" height="712" rx="150" fill="{c['bg']}"/>{shapes(stroke, c=c)}
</svg>
'''


def favicon(clip_id='c', c=C):
    # Tight crop on the peeking eyes: the only part that still reads at 16-40 px.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="520 420 360 360">
  <title>Ritrovato</title>
  <clipPath id="{clip_id}"><rect x="520" y="420" width="360" height="360" rx="72"/></clipPath>
  <g clip-path="url(#{clip_id})">
  <rect x="520" y="420" width="360" height="360" fill="{c['bg']}"/>{shapes(18, simple=True, c=c)}
  </g>
</svg>
'''


def to_jsx(svg):
    body = svg.split('\n', 2)[2].rsplit('</svg>', 1)[0]  # drop <svg ...> and <title>
    body = re.sub(r'([a-z]+)-([a-z])([a-z]*)=', lambda m: m[1] + m[2].upper() + m[3] + '=', body)
    body = re.sub(r'stroke-width', 'strokeWidth', body)
    return '\n'.join('      ' + l.strip() for l in body.strip().split('\n'))


if __name__ == '__main__':
    brand = REPO / 'docs' / 'brand'
    brand.mkdir(exist_ok=True)
    (brand / 'logo.svg').write_text(master(), encoding='utf-8')
    (brand / 'logo-icon.svg').write_text(icon(), encoding='utf-8')
    (REPO / 'web' / 'public' / 'favicon.svg').write_text(favicon(), encoding='utf-8')

    tsx = f'''// Ritrovato mark: a lost-and-found box with something peeking out.
    // Generated by docs/brand/gen_logo.py (favicon crop); edit there and regenerate.
    export default function Logo({{ size = 36, className }}: {{ size?: number; className?: string }}) {{
      return (
        <svg viewBox="520 420 360 360" width={{size}} height={{size}} className={{className}} aria-hidden="true">
    {to_jsx(favicon('ritrovato-logo-clip'))}
        </svg>
      )
    }}
    '''
    (REPO / 'web' / 'src' / 'components' / 'Logo.tsx').write_text(tsx, encoding='utf-8')
    print('ok')
